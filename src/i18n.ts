function getInitialLanguage() {
  if (typeof window === "undefined") {
    return "en";
  }

  try {
    const stored = window.localStorage.getItem("local-chat-panel:settings");
    const settings = stored ? (JSON.parse(stored) as { language?: string }) : undefined;
    return settings?.language === "zh-CN" ? "zh-CN" : "en";
  } catch {
    return "en";
  }
}

